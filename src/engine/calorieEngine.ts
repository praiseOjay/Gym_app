export const DEFAULT_MET_BY_CATEGORY = {
  cardio: 8.0,
  compoundStrength: 5.5,
  isolationStrength: 4.2,
  plyometrics: 8.5,
  flexibility: 2.5,
  restEPOC: 1.8,
  default: 5.0
};

/**
 * Returns the MET value for an exercise by ID or falls back to muscle group heuristics
 */
export function getExerciseMet(exerciseId?: string, muscleGroup?: MuscleGroup, category?: 'Compound' | 'Isolation'): number {
  if (exerciseId && EXERCISE_MET_LOOKUP[exerciseId] !== undefined) {
    return EXERCISE_MET_LOOKUP[exerciseId];
  }
  if (muscleGroup === 'Cardio') return DEFAULT_MET_BY_CATEGORY.cardio;
  if (category === 'Compound') return DEFAULT_MET_BY_CATEGORY.compoundStrength;
  if (category === 'Isolation') return DEFAULT_MET_BY_CATEGORY.isolationStrength;
  return DEFAULT_MET_BY_CATEGORY.default;
}

/**
 * Compendium of Physical Activities Formula:
 * Calories / Minute = (MET * 3.5 * bodyWeightKg) / 200
 */
export function calculateCaloriesPerMinute(met: number, bodyWeightKg: number = 75): number {
  const safeWeight = Math.max(30, Math.min(250, bodyWeightKg || 75));
  return (met * 3.5 * safeWeight) / 200;
}

/**
 * Estimates calories burned during a single completed set based on time-under-tension (TUT)
 */
export function calculateSetCalories(
  exerciseId: string,
  set: WorkoutSet,
  bodyWeightKg: number = 75,
  muscleGroup?: MuscleGroup
): number {
  if (!set.completed) return 0;
  const met = getExerciseMet(exerciseId, muscleGroup);
  const calsPerMin = calculateCaloriesPerMinute(met, bodyWeightKg);

  if (set.type === 'warmup') {
    // Warmups have lower intensity (~70% MET) and ~25s duration
    const tutMinutes = 25 / 60;
    return tutMinutes * (calsPerMin * 0.75);
  }

  // Working / Failure / Drop sets: TUT estimated at ~3.5s per rep (minimum 30s)
  const tutSeconds = Math.max(30, (set.reps || 10) * 3.5);
  const tutMinutes = tutSeconds / 60;

  // Extra metabolic demand if set was taken to failure
  const intensityFactor = set.type === 'failure' || (set.rpe && set.rpe >= 9.5) ? 1.15 : 1.0;
  return tutMinutes * calsPerMin * intensityFactor;
}

export interface SessionCalorieBreakdown {
  totalCalories: number;
  activeCalories: number;
  restCalories: number;
  avgCaloriesPerMinute: number;
  totalTutSeconds: number;
}

/**
 * Calculates total session calories including active lifting TUT and inter-set EPOC rest burn
 */
export function calculateSessionTotalCalories(
  session: WorkoutSession,
  bodyWeightKg: number = 75
): SessionCalorieBreakdown {
  const safeWeight = Math.max(30, Math.min(250, bodyWeightKg || 75));
  let activeCalories = 0;
  let totalTutSeconds = 0;

  session.exercises.forEach((ex) => {
    ex.sets.forEach((s) => {
      if (s.completed) {
        const setCal = calculateSetCalories(ex.exerciseId, s, safeWeight, ex.muscleGroup);
        activeCalories += setCal;
        const tut = s.type === 'warmup' ? 25 : Math.max(30, (s.reps || 10) * 3.5);
        totalTutSeconds += tut;
      }
    });
  });

  const durationSec = Math.max(totalTutSeconds, session.durationSeconds || 0);
  const restSeconds = Math.max(0, durationSec - totalTutSeconds);
  const restMinutes = restSeconds / 60;

  // Elevated EPOC rate during rest intervals
  const restCalPerMin = calculateCaloriesPerMinute(DEFAULT_MET_BY_CATEGORY.restEPOC, safeWeight);
  const restCalories = restMinutes * restCalPerMin;

  const totalCalories = Math.round(activeCalories + restCalories);
  const totalMinutes = Math.max(1, durationSec / 60);
  const avgCaloriesPerMinute = parseFloat((totalCalories / totalMinutes).toFixed(1));

  return {
    totalCalories,
    activeCalories: Math.round(activeCalories),
    restCalories: Math.round(restCalories),
    avgCaloriesPerMinute,
    totalTutSeconds
  };
}

/**
 * Real-time active workout calorie estimate ticking smoothly during live training
 */
export function estimateLiveSessionCalories(
  exercises: WorkoutExercise[],
  elapsedSeconds: number,
  bodyWeightKg: number = 75
): number {
  const safeWeight = Math.max(30, Math.min(250, bodyWeightKg || 75));
  let completedSetCalories = 0;
  let completedTutSec = 0;

  exercises.forEach((ex) => {
    ex.sets.forEach((s) => {
      if (s.completed) {
        completedSetCalories += calculateSetCalories(ex.exerciseId, s, safeWeight, ex.muscleGroup);
        completedTutSec += s.type === 'warmup' ? 25 : Math.max(30, (s.reps || 10) * 3.5);
      }
    });
  });

  const elapsed = Math.max(completedTutSec, elapsedSeconds || 0);
  const restSec = Math.max(0, elapsed - completedTutSec);
  const restMinutes = restSec / 60;
  const restCalPerMin = calculateCaloriesPerMinute(DEFAULT_MET_BY_CATEGORY.restEPOC, safeWeight);
  const restCalories = restMinutes * restCalPerMin;

  // If no sets are logged yet, basal gym preparation rate (~2.5 MET)
  if (completedTutSec === 0) {
    const prepCalPerMin = calculateCaloriesPerMinute(2.5, safeWeight);
    return Math.max(1, Math.round((elapsed / 60) * prepCalPerMin));
  }

  return Math.max(1, Math.round(completedSetCalories + restCalories));
}
